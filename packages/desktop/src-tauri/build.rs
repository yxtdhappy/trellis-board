//! 把本机插件宿主、6 个内置插件与 trellis-kit 嵌入 EXE（单文件绿色包），运行时按内容戳释放。
//!
//! 生成 `OUT_DIR/embedded_assets.rs` 与 `OUT_DIR/embedded_kit_assets.rs`：
//! 每一项是 `(运行时相对路径, include_str!(源文件))`。保持单个 EXE，不新增运行时依赖。

use std::fs;
use std::path::{Path, PathBuf};

const BUILTIN_PLUGINS: &[&str] = &[
    "witops-core",
    "scenario-copilot",
    "jenkins-ops",
    "accounts-core",
    "acp-dispatch",
    "a2a-intake",
];

const SKIP_DIRS: &[&str] = &[
    "node_modules",
    "public",
    "data",
    "dist",
    "build",
    "test",
    "tests",
    "venv",
    ".venv",
    "__pycache__",
    ".git",
    "target",
];

fn main() {
    println!("cargo:rerun-if-env-changed=TRELLIS_UPDATE_SERVER");
    println!("cargo:rerun-if-env-changed=TRELLIS_BOARD_APP_NAME");
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let repo_root = manifest_dir
        .join("..")
        .join("..")
        .join("..")
        .canonicalize()
        .expect("无法定位仓库根目录");
    if std::env::var_os("TRELLIS_BOARD_APP_NAME").is_none() {
        let env_path = repo_root.join(".env");
        println!("cargo:rerun-if-changed={}", env_path.display());
        if let Some(app_name) = read_dot_env_value(&env_path, "TRELLIS_BOARD_APP_NAME") {
            println!("cargo:rustc-env=TRELLIS_BOARD_APP_NAME={app_name}");
        }
    }

    let mut assets: Vec<(String, PathBuf)> = Vec::new();
    collect_tree(
        &repo_root.join("packages").join("server"),
        &repo_root,
        &mut assets,
    );
    collect_tree(
        &repo_root.join("packages").join("shared"),
        &repo_root,
        &mut assets,
    );
    for plugin in BUILTIN_PLUGINS {
        collect_tree(
            &repo_root.join("plugins").join(plugin),
            &repo_root,
            &mut assets,
        );
    }
    let host = repo_root
        .join("packages")
        .join("desktop")
        .join("plugin-host")
        .join("host.mjs");
    if host.is_file() {
        println!("cargo:rerun-if-changed={}", host.display());
        assets.push(("host.mjs".to_string(), host));
    }

    assets.sort_by(|left, right| left.0.cmp(&right.0));
    assets.dedup_by(|left, right| left.0 == right.0);

    let kit_dir = repo_root.join("trellis-kit");
    let mut kit_assets: Vec<(String, PathBuf)> = Vec::new();
    collect_kit_tree(&kit_dir, &kit_dir, &mut kit_assets);
    kit_assets.sort_by(|left, right| left.0.cmp(&right.0));
    kit_assets.dedup_by(|left, right| left.0 == right.0);
    if kit_assets.is_empty() {
        panic!("trellis-kit 为空或不存在：{}", kit_dir.display());
    }

    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for (dest, source) in &assets {
        for byte in dest.as_bytes() {
            hash ^= u64::from(*byte);
            hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
        if let Ok(bytes) = fs::read(source) {
            for byte in bytes {
                hash ^= u64::from(byte);
                hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
            }
        }
    }

    let mut output = String::new();
    output.push_str("// @generated by build.rs: 本机插件运行时资源清单。\n");
    output.push_str(&format!(
        "pub static ASSET_STAMP: &str = \"{:016x}\";\n",
        hash
    ));
    output.push_str("pub static RUNTIME_ASSETS: &[(&str, &str)] = &[\n");
    for (dest, source) in &assets {
        let source = source.display().to_string().replace('\\', "/");
        output.push_str(&format!("    ({:?}, include_str!({:?})),\n", dest, source));
    }
    output.push_str("];\n");

    let mut kit_hash: u64 = 0xcbf2_9ce4_8422_2325;
    for (dest, source) in &kit_assets {
        for byte in dest.as_bytes() {
            kit_hash ^= u64::from(*byte);
            kit_hash = kit_hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
        let bytes = fs::read(source)
            .unwrap_or_else(|error| panic!("无法读取 trellis-kit 文件 {}：{error}", source.display()));
        for byte in bytes {
            kit_hash ^= u64::from(byte);
            kit_hash = kit_hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }

    let mut kit_output = String::new();
    kit_output.push_str("// @generated by build.rs: trellis-kit 嵌入资源清单。\n");
    kit_output.push_str(&format!(
        "pub static KIT_ASSET_STAMP: &str = \"{:016x}\";\n",
        kit_hash
    ));
    kit_output.push_str("pub static KIT_ASSETS: &[(&str, &str)] = &[\n");
    for (dest, source) in &kit_assets {
        let source = source.display().to_string().replace('\\', "/");
        kit_output.push_str(&format!("    ({:?}, include_str!({:?})),\n", dest, source));
    }
    kit_output.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("embedded_assets.rs"), output).expect("无法写入嵌入资源清单");
    fs::write(out_dir.join("embedded_kit_assets.rs"), kit_output)
        .expect("无法写入 trellis-kit 嵌入资源清单");

    // headless 构建（`--no-default-features`）不产出桌面壳，跳过 Tauri 上下文生成。
    if std::env::var_os("CARGO_FEATURE_DESKTOP").is_some() {
        tauri_build::build();
    }
}

fn collect_kit_tree(root: &Path, kit_root: &Path, assets: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", root.display());
    if !root.is_dir() {
        return;
    }
    walk_kit(root, kit_root, assets);
}

fn walk_kit(directory: &Path, kit_root: &Path, assets: &mut Vec<(String, PathBuf)>) {
    const SKIP_KIT_DIRS: &[&str] = &["__pycache__", ".git"];
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        if path.is_dir() {
            if SKIP_KIT_DIRS.contains(&name.as_str()) {
                continue;
            }
            walk_kit(&path, kit_root, assets);
            continue;
        }
        let Ok(relative) = path.strip_prefix(kit_root) else {
            continue;
        };
        // include_str! 要求 UTF-8；在构建期给出明确错误，避免生成到一半才失败。
        fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("trellis-kit 文件必须是 UTF-8 文本 {}：{error}", path.display()));
        let destination = relative.to_string_lossy().replace('\\', "/");
        assets.push((destination, path));
    }
}

fn collect_tree(root: &Path, repo_root: &Path, assets: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", root.display());
    if !root.is_dir() {
        return;
    }
    walk(root, repo_root, assets);
}

fn walk(directory: &Path, repo_root: &Path, assets: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        if path.is_dir() {
            if SKIP_DIRS.contains(&name.as_str()) {
                continue;
            }
            walk(&path, repo_root, assets);
            continue;
        }
        if !is_embeddable(&name) {
            continue;
        }
        let Ok(relative) = path.strip_prefix(repo_root) else {
            continue;
        };
        let Some(destination) = destination_for(relative) else {
            continue;
        };
        assets.push((destination, path));
    }
}

fn is_embeddable(name: &str) -> bool {
    if name.ends_with(".test.js") || name.ends_with(".test.mjs") {
        return false;
    }
    matches!(
        Path::new(name).extension().and_then(|value| value.to_str()),
        Some("js" | "mjs" | "cjs" | "json" | "css" | "html" | "svg" | "png" | "ico" | "woff2")
    )
}

fn destination_for(relative: &Path) -> Option<String> {
    let text = relative.to_string_lossy().replace('\\', "/");
    if let Some(rest) = text.strip_prefix("packages/server/plugin-ui/") {
        return Some(format!("plugin-ui/{rest}"));
    }
    if let Some(rest) = text.strip_prefix("packages/server/") {
        if rest.starts_with("plugin-ui/") {
            return None;
        }
        return Some(format!("node_modules/@trellis-board/server/{rest}"));
    }
    if let Some(rest) = text.strip_prefix("packages/shared/") {
        return Some(format!("node_modules/@trellis-board/shared/{rest}"));
    }
    if let Some(rest) = text.strip_prefix("packages/desktop/plugin-host/host.mjs") {
        let _ = rest;
        return Some("host.mjs".to_string());
    }
    for plugin in BUILTIN_PLUGINS {
        if let Some(rest) = text.strip_prefix(&format!("plugins/{plugin}/")) {
            return Some(format!("plugins/{plugin}/{rest}"));
        }
    }
    None
}

fn read_dot_env_value(path: &Path, target_key: &str) -> Option<String> {
    let content = fs::read_to_string(path).ok()?;
    for raw_line in content.lines() {
        let trimmed = raw_line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let line = trimmed.strip_prefix("export ").unwrap_or(trimmed).trim();
        let Some((key, raw_value)) = line.split_once('=') else {
            continue;
        };
        if key.trim() != target_key {
            continue;
        }
        let value = raw_value.trim();
        let unquoted = if (value.starts_with('"') && value.ends_with('"') && value.len() >= 2)
            || (value.starts_with('\'') && value.ends_with('\'') && value.len() >= 2)
        {
            &value[1..value.len() - 1]
        } else {
            value.split(" #").next().unwrap_or(value).trim()
        };
        let cleaned = unquoted.trim();
        if !cleaned.is_empty() {
            return Some(cleaned.to_string());
        }
    }
    None
}
